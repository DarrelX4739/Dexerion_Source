'use strict';

// Build the shell's small Lucide registry from the pinned upstream UMD bundle.
// The original renderer helpers are retained verbatim so attributes, SVG
// geometry, accessibility and startup timing do not depend on a new loader.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

const APP = path.join(__dirname, '../../code');
const UPSTREAM = path.join(APP, 'assets/vendor/lucide.min.js');
const TARGET = path.join(APP, 'assets/vendor/lucide-shell.js');
const SHELL = path.join(APP, 'src/renderer/shell.html');
// ai-artifacts.js creates this icon on detached cards, not via data-lucide.
const DYNAMIC = ['Ellipsis', 'MoreHorizontal'];

function generate() {
  const upstream = fs.readFileSync(UPSTREAM, 'utf8');
  const html = fs.readFileSync(SHELL, 'utf8');
  const { icons } = require(UPSTREAM);
  const staticIcons = [...html.matchAll(/\bdata-lucide\s*=\s*["']([\w-]+)["']/g)]
    .map(([, name]) => name.replace(/(^|-)(\w)/g, (_, prefix, c) => c.toUpperCase()));
  assert.ok(staticIcons.length > 0, 'shell must have static Lucide placeholders');
  const names = [...new Set([...staticIcons, ...DYNAMIC])].sort();
  const selected = {};
  for (const name of names) {
    assert.ok(Object.hasOwn(icons, name), 'unknown Lucide icon: ' + name);
    selected[name] = icons[name];
  }

  // Boundaries from pinned v1.55.0: UMD wrapper, renderer helpers up to the
  // first glyph, then createIcons just before the global export assignments.
  // If an upstream upgrade changes either delimiter, fail rather than emit an
  // approximate bundle. Recheck SVG parity when updating these boundaries.
  const firstGlyph = upstream.indexOf(',Ka=[["path"');
  const createIcons = upstream.indexOf('const cS=({icons:h=dS,');
  const firstExport = upstream.indexOf(';a.AArrowDown=Ka,', createIcons);
  assert.ok(firstGlyph > 0 && createIcons > firstGlyph && firstExport > createIcons,
    'unsupported Lucide UMD layout; check the pinned upstream helpers');

  return '// Generated by code/build/scripts/vendor-lucide-shell.cjs. Do not edit.\n'
    + upstream.slice(0, firstGlyph) + ';\nconst dS=Object.freeze(' + JSON.stringify(selected) + ');\n'
    + upstream.slice(createIcons, firstExport) + ';\n'
    + names.map((name) => 'a.' + name + '=dS.' + name).join(',') + ','
    + 'a.createElement=Ia,a.createIcons=cS,a.icons=dS}));\n';
}

if (require.main === module) {
  const content = generate();
  if (process.argv.includes('--check')) {
    assert.equal(fs.readFileSync(TARGET, 'utf8'), content,
      'shell Lucide registry is stale; run node code/build/scripts/vendor-lucide-shell.cjs');
  } else {
    fs.writeFileSync(TARGET, content);
  }
}
module.exports = { generate, TARGET, UPSTREAM, SHELL };
